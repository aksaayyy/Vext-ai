/**
 * generateExecutionPack — maps card output fields to a zip-ready file map.
 * Returns Record<path, utf-8 string content>
 */

export interface CardData {
  shareId: string;
  title: string | null;
  classification: string;
  output: unknown;
  createdAt: Date;
}

// ── Simple YAML serialiser (handles 1-level nesting) ─────────────────────────
function toYaml(obj: Record<string, unknown>, indent = 0): string {
  const pad = '  '.repeat(indent);
  return Object.entries(obj)
    .map(([k, v]) => {
      if (v == null) return `${pad}${k}: ~`;
      if (typeof v === 'object' && !Array.isArray(v)) {
        return `${pad}${k}:\n${toYaml(v as Record<string, unknown>, indent + 1)}`;
      }
      if (Array.isArray(v)) {
        const items = (v as unknown[]).map(i => `${pad}  - ${String(i)}`).join('\n');
        return `${pad}${k}:\n${items}`;
      }
      // Quote strings that need it
      const s = String(v);
      const needsQuote = s.includes(':') || s.includes('#') || s.includes('\n') || s.includes('"');
      return `${pad}${k}: ${needsQuote ? `"${s.replace(/"/g, '\\"')}"` : s}`;
    })
    .join('\n');
}

// ── Checklist builder ─────────────────────────────────────────────────────────
function checklist(items: string[], header = ''): string {
  const lines = items.map(item => `- [ ] ${item}`).join('\n');
  return header ? `${header}\n\n${lines}` : lines;
}

// ── Python test scaffold ──────────────────────────────────────────────────────
function pythonTestScaffold(title: string, steps: string[]): string {
  const testFns = steps.slice(0, 3).map((step, i) => {
    const name = step.replace(/[^a-zA-Z0-9 ]/g, '').replace(/\s+/g, '_').toLowerCase().slice(0, 40) || `step_${i + 1}`;
    return `def test_${name}():\n    # TODO: implement test for: ${step}\n    pass`;
  });

  return `"""
Starter tests for: ${title}
Generated by Vext — https://vext.so
"""

import pytest


${testFns.join('\n\n')}


if __name__ == "__main__":
    pytest.main([__file__, "-v"])
`;
}

// ── Per-classification file generators ───────────────────────────────────────

type FileMap = Record<string, string>;

function packSetupTutorial(data: CardData): FileMap {
  const o = data.output as any;
  const title = data.title ?? 'Setup Tutorial';
  const steps: string[] = o.steps ?? [];
  const snippets: Record<string, string> = o.configSnippets ?? {};
  const files: string[] = o.generatedFiles ?? [];

  const systemPrompt = `# System Prompt — ${title}

You are an expert assistant helping implement the following setup/tutorial exactly as described.

## Your Role
Guide the user through each step precisely. If they get stuck, refer to the numbered steps below.
Do not skip steps. Confirm completion before moving to the next.

## Steps to Follow
${steps.map((s, i) => `${i + 1}. ${s}`).join('\n')}

${files.length ? `## Files to Create/Modify\n${files.map(f => `- \`${f}\``).join('\n')}` : ''}

## Rules
- Follow steps in order.
- Use exact config values provided.
- Ask clarifying questions only if a step is ambiguous.
- Confirm each step is complete before proceeding.
`.trimEnd();

  const configYaml = `# Vext Config — ${title}
# Generated: ${new Date().toISOString()}

metadata:
  title: "${title}"
  classification: setup/tutorial
  share_id: "${data.shareId}"

${Object.keys(snippets).length > 0 ? `config_snippets:\n${Object.entries(snippets).map(([k, v]) => `  ${k}: |\n    ${v.replace(/\n/g, '\n    ')}`).join('\n')}` : '# No config snippets extracted'}

generated_files:
${files.length ? files.map(f => `  - "${f}"`).join('\n') : '  []'}
`;

  const md = `# Setup Checklist — ${title}

> Generated by [Vext](https://vext.so/card/${data.shareId}) on ${new Date().toLocaleDateString()}

## Steps

${checklist(steps)}

${files.length ? `## Files to Create\n\n${files.map(f => `- [ ] \`${f}\``).join('\n')}` : ''}
`.trimEnd();

  const files_map: FileMap = {
    'prompts/system-prompt.md': systemPrompt,
    'configs/config.yaml': configYaml,
    'scripts/setup-checklist.md': md,
  };

  if (Object.keys(snippets).length > 0) {
    files_map['tests/starter-test.py'] = pythonTestScaffold(title, steps);
  }

  return files_map;
}

