function packToolDemo(data: CardData): FileMap {
  const o = data.output as any;
  const title = data.title ?? 'Tool Demo';
  const toolName: string = o.toolName ?? 'Tool';
  const features: string[] = o.features ?? [];
  const useCases: string[] = o.useCases ?? [];
  const pros: string[] = o.prosCons?.pros ?? [];
  const cons: string[] = o.prosCons?.cons ?? [];

  const systemPrompt = `# System Prompt — ${title}

You are an expert on ${toolName}. Help the user understand and use it effectively.

## Tool: ${toolName}

## Key Features
${features.map(f => `- ${f}`).join('\n')}

## Primary Use Cases
${useCases.map((u, i) => `${i + 1}. ${u}`).join('\n')}

## Strengths & Limitations
**Strengths:** ${pros.join(', ')}
**Limitations:** ${cons.join(', ')}

## Instructions
Provide concrete examples for each feature. Always acknowledge limitations honestly.
Recommend ${toolName} only when it genuinely fits the use case.
`.trimEnd();

  const configYaml = `# Vext Config — ${toolName} Demo
# Generated: ${new Date().toISOString()}

metadata:
  title: "${title}"
  classification: tool/demo
  tool_name: "${toolName}"
  share_id: "${data.shareId}"

evaluation:
  pros:
${pros.map(p => `    - "${p.replace(/"/g, '\\"')}"`).join('\n') || '    []'}
  cons:
${cons.map(c => `    - "${c.replace(/"/g, '\\"')}"`).join('\n') || '    []'}

use_cases:
${useCases.map(u => `  - "${u.replace(/"/g, '\\"')}"`).join('\n') || '  []'}
`;

  const md = `# ${toolName} Evaluation Checklist

> Generated by [Vext](https://vext.so/card/${data.shareId})

## Features to Test

${checklist(features)}

## Use Cases to Validate

${checklist(useCases)}

## Pros vs Cons

| Pros | Cons |
|------|------|
${Math.max(pros.length, cons.length) > 0
    ? Array.from({ length: Math.max(pros.length, cons.length) })
        .map((_, i) => `| ${pros[i] ?? ''} | ${cons[i] ?? ''} |`)
        .join('\n')
    : '| — | — |'}
`.trimEnd();

  return {
    'prompts/system-prompt.md': systemPrompt,
    'configs/config.yaml': configYaml,
    'scripts/setup-checklist.md': md,
    'tests/starter-test.py': pythonTestScaffold(toolName, features),
  };
}

function packFinanceSetup(data: CardData): FileMap {
  const o = data.output as any;
  const title = data.title ?? 'Finance Setup';
  const strategy: string = o.strategy ?? '';
  const riskParams: Record<string, string> = o.riskParameters ?? {};
  const backtest = o.backtestResults ?? {};
  const snippets: Record<string, string> = o.configSnippets ?? {};

  const systemPrompt = `# System Prompt — ${title}

You are a quantitative trading assistant implementing the following strategy.

## Strategy
${strategy}

## Risk Parameters
${Object.entries(riskParams).map(([k, v]) => `- **${k}**: ${v}`).join('\n')}

${backtest && Object.keys(backtest).length
    ? `## Backtest Performance\n${[
        backtest.sharpeRatio != null ? `- Sharpe Ratio: ${backtest.sharpeRatio}` : '',
        backtest.maxDrawdown != null ? `- Max Drawdown: ${backtest.maxDrawdown}%` : '',
        backtest.winRate != null ? `- Win Rate: ${backtest.winRate}%` : '',
      ].filter(Boolean).join('\n')}`
    : ''}

## Instructions
Implement trades ONLY within the defined risk parameters.
Always confirm current market conditions before execution.
Never override the risk limits. Log all decisions with rationale.

## ⚠️ Disclaimer
This is educational content only — not financial advice.
`.trimEnd();

  const configYaml = `# Vext Finance Config — ${title}
# Generated: ${new Date().toISOString()}
# ⚠️ DISCLAIMER: Educational only. Not financial advice.

metadata:
  title: "${title}"
  classification: finance/setup
  share_id: "${data.shareId}"

strategy:
  description: "${strategy.replace(/"/g, '\\"').slice(0, 200)}"

risk_parameters:
${Object.entries(riskParams).map(([k, v]) => `  ${k}: "${v}"`).join('\n') || '  {}'}

backtest_results:
${backtest.sharpeRatio != null ? `  sharpe_ratio: ${backtest.sharpeRatio}` : '  sharpe_ratio: ~'}
${backtest.maxDrawdown != null ? `  max_drawdown_pct: ${backtest.maxDrawdown}` : '  max_drawdown_pct: ~'}
${backtest.winRate != null ? `  win_rate_pct: ${backtest.winRate}` : '  win_rate_pct: ~'}

${Object.keys(snippets).length ? `config_snippets:\n${Object.entries(snippets).map(([k, v]) => `  ${k}: |\n    ${v.replace(/\n/g, '\n    ')}`).join('\n')}` : ''}
`;

  const md = `# Finance Setup Checklist — ${title}

> Generated by [Vext](https://vext.so/card/${data.shareId})
> ⚠️ Educational purposes only — not financial advice.

## Strategy Overview
${strategy}

## Pre-Trade Checklist

- [ ] Verify all risk parameters are configured
- [ ] Confirm backtesting is complete
- [ ] Paper trade for minimum 2 weeks
- [ ] Set stop-loss levels per risk params
- [ ] Define position sizing rules
- [ ] Configure alerts and monitoring

## Risk Parameters

${Object.entries(riskParams).map(([k, v]) => `- [ ] **${k}**: ${v}`).join('\n') || '- [ ] Define risk parameters'}
`.trimEnd();

  return {
    'prompts/system-prompt.md': systemPrompt,
    'configs/config.yaml': configYaml,
    'scripts/setup-checklist.md': md,
    'tests/starter-test.py': pythonTestScaffold(title, Object.keys(riskParams).map(k => `Validate ${k} = ${riskParams[k]}`)),
  };
}

